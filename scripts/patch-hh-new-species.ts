/**
 * Haunted Hollow's new species and Mart prices (docs/26 §2.8, the user's calls of 2026-10-15), as a patch over content
 * that has the world already: Joltik, Riolu, Galvantula and Lucario join four wild pools, and the Mart sells the Link
 * Cable for ₽300 and the Master Ball for ₽999 (still 1 per player). Nothing else is touched, so the admin's own edits
 * (the world's dates, its switch, any other price or pool) stay as they are.
 *
 * `tsx scripts/patch-hh-new-species.ts <in-bundle.json> <out-bundle.json>` patches an admin export for
 * `pnpm import-bundle`; `tsx scripts/patch-hh-new-species.ts --sql <out.sql>` writes the same as a migration
 * (supabase/migrations/0055_hh_new_species.sql). The rows are the content script's, same stable ids, so fresh content
 * (`pnpm haunted-hollow`) and patched content agree.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { BundleRaw, SmallWorld, WildPoolEntry } from '../src/engine/types'
import { AREAS, REGION_ID, WORLD_ID, haunted } from './content-haunted-hollow'

/** Each new species and the area (content key) it is found in. */
export const NEW_SPECIES: [areaKey: string, dex: number][] = [
  ['whispering-woods', 595],
  ['old-quarry', 447],
  ['rusted-armory', 596],
  ['spirit-mountain', 448],
]

/** The Mart's new prices, by item key; the limits stay (the Master Ball's 1 per player). */
export const NEW_PRICES: Record<string, number> = { 'link-cable': 300, 'master-ball': 999 }

/** The new pool rows, each with its area's id, exactly as the content script builds them. */
export function newWildRows(): { areaId: string; entry: WildPoolEntry }[] {
  const areas = haunted().areas
  return NEW_SPECIES.map(([key, dex]) => {
    const area = areas[AREAS.findIndex((a) => a.key === key)]
    const entry = area?.wildPool.find((w) => w.dex === dex)
    if (!area || !entry) throw new Error(`content-haunted-hollow.ts has no #${dex} in ${key}`)
    return { areaId: area.id, entry }
  })
}

type Shop = SmallWorld['shop']
const repriced = (shop: Shop): Shop =>
  shop.map((s) => (s.key in NEW_PRICES ? { ...s, price: NEW_PRICES[s.key]! } : s))

/** The export with this change in it. A species its area holds already is left as it is; so is a removed Mart line. */
export function patchHhNewSpecies(b: BundleRaw): BundleRaw {
  const rows = newWildRows()
  if (!b.areas.some((a) => a.regionId === REGION_ID))
    throw new Error('This export has no Haunted Hollow: add it first (pnpm haunted-hollow)')
  const config = b.config as Record<string, unknown> & {
    smallWorlds?: { access?: string; list?: SmallWorld[] }
  }
  const worlds = config.smallWorlds
  return {
    ...b,
    areas: b.areas.map((a) => {
      const add = rows
        .filter((r) => r.areaId === a.id && !a.wildPool.some((w) => w.dex === r.entry.dex))
        .map((r) => r.entry)
      return add.length ? { ...a, wildPool: [...a.wildPool, ...add] } : a
    }),
    config: {
      ...config,
      configVersion: Number(config.configVersion ?? 0) + 1,
      ...(worlds?.list && {
        smallWorlds: {
          ...worlds,
          list: worlds.list.map((w) => (w.id === WORLD_ID && w.shop ? { ...w, shop: repriced(w.shop) } : w)),
        },
      }),
    },
  }
}

const q = (v: string) => `'${v.replace(/'/g, "''")}'`

/**
 * The same as SQL for a live database that ran 0052. Each pool row goes in once, only where its area exists and does
 * not hold that species yet (an admin's own row for it wins); the prices change in the world's Mart by item key, its
 * other lines, limits and settings kept; `configVersion` + 1 so players fetch the new content. Safe to run again.
 */
export function hhNewSpeciesSql(): string {
  const values = newWildRows()
    .map(
      ({ areaId, entry: w }) =>
        `  (${q(w.id)}, ${q(areaId)}, ${w.dex}, ${w.weight}, ${w.minLevel}, ${w.maxLevel})`,
    )
    .join(',\n')
  const prices = Object.entries(NEW_PRICES)
    .map(([key, price]) => `          when ${q(key)} then jsonb_set(s, '{price}', '${price}')`)
    .join('\n')
  return [
    "-- Haunted Hollow's new species and Mart prices (docs/26 §2.8). Generated by",
    '-- `tsx scripts/patch-hh-new-species.ts --sql`: do not edit by hand. Patches only what changed since 0052, over the',
    "-- admin's later edits: four wild-pool rows (Joltik, Riolu, Galvantula, Lucario) and two prices in the world's Mart",
    '-- (Link Cable ₽300, Master Ball ₽999, its limit kept), then `configVersion` + 1. Safe to run again.',
    'begin;',
    `insert into area_wild_pool (id, area_id, dex, weight, min_level, max_level)
select v.id::uuid, v.area_id::uuid, v.dex, v.weight, v.min_level, v.max_level
from (values
${values}
) v (id, area_id, dex, weight, min_level, max_level)
where exists (select 1 from areas a where a.id = v.area_id::uuid)
  and not exists (select 1 from area_wild_pool p where p.area_id = v.area_id::uuid and p.dex = v.dex)
on conflict (id) do nothing;`,
    `update game_config set value = jsonb_set(value, '{list}', (
  select coalesce(jsonb_agg(
    case when w ->> 'id' = ${q(WORLD_ID)} and jsonb_typeof(w -> 'shop') = 'array' then jsonb_set(w, '{shop}', (
      select coalesce(jsonb_agg(
        case s ->> 'key'
${prices}
          else s end
        order by i), '[]'::jsonb)
      from jsonb_array_elements(w -> 'shop') with ordinality t (s, i)))
    else w end
  order by n), '[]'::jsonb)
  from jsonb_array_elements(value -> 'list') with ordinality u (w, n)))
where key = 'smallWorlds' and jsonb_typeof(value -> 'list') = 'array';`,
    "insert into game_config (key, value) values ('configVersion', '1'::jsonb) on conflict (key) do update set value = to_jsonb(coalesce((game_config.value #>> '{}')::int, 0) + 1);",
    'commit;',
    '',
  ].join('\n')
}

async function main() {
  const args = process.argv.slice(2)
  if (args[0] === '--sql') {
    if (!args[1]) throw new Error('Usage: tsx scripts/patch-hh-new-species.ts --sql <out.sql>')
    await writeFile(path.resolve(args[1]), hhNewSpeciesSql())
    console.log(`✓ Haunted Hollow new species SQL → ${args[1]}`)
    return
  }
  const [input, output] = args
  if (!input || !output)
    throw new Error(
      'Usage: tsx scripts/patch-hh-new-species.ts <in-bundle.json> <out-bundle.json> | --sql <out.sql>',
    )
  const b = JSON.parse(await readFile(path.resolve(input), 'utf8')) as BundleRaw
  await writeFile(path.resolve(output), JSON.stringify(patchHhNewSpecies(b)))
  console.log(`✓ Haunted Hollow: ${NEW_SPECIES.length} species added, Mart repriced → ${output}`)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
