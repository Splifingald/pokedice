/**
 * Distortion World's portal run (docs/28, the user's spec of 2026-10-15), as a patch over content that has Haunted
 * Hollow already: the area opens at 100 Pokémon in the world's Pokédex (it was 119), and gets its portal run (`mode`,
 * every number the admin's after that). Nothing else is touched, so the admin's own edits stay as they are.
 *
 * `tsx scripts/patch-hh-distortion.ts <in-bundle.json> <out-bundle.json>` patches an admin export for
 * `pnpm import-bundle`; `tsx scripts/patch-hh-distortion.ts --sql <out.sql>` writes the migration
 * (supabase/migrations/0057_hh_distortion_world.sql): the same content patch, plus the switch's row and the server's
 * checks (the raid's team cap, and the raid closed until the run is won). The values are the content script's, so fresh
 * content (`pnpm haunted-hollow`) and patched content agree.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Area, BundleRaw, UnlockCondition } from '../src/engine/types'
import { AREAS, REGION_ID, haunted } from './content-haunted-hollow'

/** The count 0052 wrote, which this patch replaces (an admin's other count is theirs: left alone). */
export const OLD_COUNT = 119

/** Distortion World as the content script builds it now: its id, its new count and its mode. */
export function distortionArea(): Area {
  const i = AREAS.findIndex((a) => a.key === 'distortion-world')
  const area = haunted().areas[i]
  if (!area?.mode) throw new Error('content-haunted-hollow.ts has no portal run on Distortion World')
  return area
}

export const newCount = (): number => {
  const c = distortionArea().unlockConditions?.find((x) => x.kind === 'pokedex')
  if (c?.kind !== 'pokedex') throw new Error('Distortion World has no Pokédex condition')
  return c.count
}

const recount = (conds: UnlockCondition[] | null): UnlockCondition[] | null =>
  conds?.map((c) => (c.kind === 'pokedex' && c.count === OLD_COUNT ? { ...c, count: newCount() } : c)) ??
  conds

/** The export with this change in it: the count when it is still 0052's, the mode when the area has none. */
export function patchHhDistortion(b: BundleRaw): BundleRaw {
  const dw = distortionArea()
  if (!b.areas.some((a) => a.regionId === REGION_ID))
    throw new Error('This export has no Haunted Hollow: add it first (pnpm haunted-hollow)')
  const config = b.config as Record<string, unknown>
  return {
    ...b,
    areas: b.areas.map((a) =>
      a.id === dw.id ? { ...a, unlockConditions: recount(a.unlockConditions), mode: a.mode ?? dw.mode } : a,
    ),
    config: {
      ...config,
      configVersion: Number(config.configVersion ?? 0) + 1,
      // The switch stays where the admin left it; Off when there is none yet (docs/15 §20).
      portalRun: config.portalRun ?? { access: 'off' },
    },
  }
}

const q = (v: string) => `'${v.replace(/'/g, "''")}'`

/** 0046's and 0045's raid functions, now aware of a portal area's raid; the rest of the migration around them. */
export function hhDistortionSql(): string {
  const dw = distortionArea()
  return [
    "-- Distortion World's portal run (docs/28). Generated by `tsx scripts/patch-hh-distortion.ts --sql`: do not edit by",
    '-- hand. Run after 0052 (and 0055); safe to run again. It patches only what this feature changes, over the',
    "-- admin's later edits:",
    "--  1. areas.mode, a new column: an area's special mode. Distortion World gets its portal run (when it has no mode",
    `--     yet) and opens at ${newCount()} Pokémon in the world's Pokédex (only where 0052's count, ${OLD_COUNT}, is still there).`,
    '--  2. game_config `portalRun`: the switch, Off (left alone when there).',
    "--  3. The server's checks: a portal area's raid takes teams up to its own cap, and stays shut (teams, close) until",
    "--     the player's cloud save says its run is won, while the switch is on for them.",
    '--  4. configVersion + 1, so players fetch the new content.',
    'begin;',
    '',
    'alter table areas add column if not exists mode jsonb;',
    '',
    `update areas set unlock_conditions = (
  select jsonb_agg(case when c ->> 'kind' = 'pokedex' and (c ->> 'count')::int = ${OLD_COUNT}
                        then jsonb_set(c, '{count}', '${newCount()}') else c end order by i)
  from jsonb_array_elements(unlock_conditions) with ordinality t (c, i))
where id = ${q(dw.id)} and jsonb_typeof(unlock_conditions) = 'array' and jsonb_array_length(unlock_conditions) > 0;`,
    `update areas set mode = ${q(JSON.stringify(dw.mode))}::jsonb where id = ${q(dw.id)} and mode is null;`,
    '',
    `insert into game_config (key, value) values ('portalRun', '{"access": "off"}'::jsonb) on conflict (key) do nothing;`,
    '',
    SERVER_SQL,
    '',
    "insert into game_config (key, value) values ('configVersion', '1'::jsonb) on conflict (key) do update set value = to_jsonb(coalesce((game_config.value #>> '{}')::int, 0) + 1);",
    'commit;',
    '',
  ].join('\n')
}

const SERVER_SQL = `-- The switch, as general_open reads its own: on for everyone, or for the admin only. Never null: an odd value is off.
create or replace function portal_run_open()
returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(a = 'all' or (a = 'admin' and is_admin()), false)
  from (select coalesce((select value ->> 'access' from game_config where key = 'portalRun'), 'off') a) x
$$;

-- A raid key's area mode when it is a portal run and the switch is on for the caller (else null: the raid is as before).
create or replace function raid_progress_portal(p_key text)
returns jsonb
language sql stable security definer set search_path = public as $$
  select a.mode from areas a
  where a.id::text = split_part(p_key, ':', 1) and a.mode ->> 'kind' = 'portal' and portal_run_open()
$$;

-- The caller's cloud save says the portal run of this raid's area is won (the live block, or the parked one).
create or replace function raid_progress_portal_won(p_key text, p_realm text)
returns boolean
language plpgsql stable security definer set search_path = public as $$
begin
  return coalesce((
    select (case when coalesce(d ->> 'region', 'kanto') = a.region_id then d -> 'areaProgress'
                 else d -> 'parked' -> a.region_id -> 'areaProgress' end
            -> a.id::text -> 'portal' ->> 'won')::boolean
    from areas a, (select s.data || '{}'::jsonb d from saves s where s.user_id = auth.uid() and s.realm = p_realm) x
    where a.id::text = split_part(p_key, ':', 1)), false);
end $$;

-- 0046's, with a portal area's raid: teams up to its own cap, and only once its run is won.
create or replace function raid_progress_set_team(p_key text, p_region text, p_ids text[], p_realm text default 'main')
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  me uuid := auth.uid();
  dex int := raid_progress_dex(p_key);
  region text := (select a.region_id from areas a where a.id::text = split_part(p_key, ':', 1));
  portal jsonb := raid_progress_portal(p_key);
  save jsonb;
  box jsonb;
  cap int;
  new_team jsonb;
begin
  if me is null then raise exception 'events_signed_out'; end if;
  if dex is null or region is null then raise exception 'events_bad_raid'; end if;
  if p_ids is null or coalesce(array_length(p_ids, 1), 0) not between 1 and 3
     or (select count(distinct x) from unnest(p_ids) x) <> array_length(p_ids, 1) then
    raise exception 'events_team_size';
  end if;
  select s.data into save from saves s where s.user_id = me and s.realm = p_realm;
  if save is null then raise exception 'events_no_save'; end if;
  if portal is not null and not raid_progress_portal_won(p_key, p_realm) then raise exception 'events_raid_locked'; end if;
  -- The Box being played is the save's top-level one (a small world's while inside it); the others are parked.
  box := case when coalesce(save ->> 'region', 'kanto') = region then save -> 'box' else save -> 'parked' -> region -> 'box' end;
  -- (greatest/least skip nulls: a plain raid's null cap must stay null to fall back.)
  cap := coalesce(case when portal -> 'raid' ? 'teamCap' then least(100, greatest(1, (portal -> 'raid' ->> 'teamCap')::int)) end,
                  raid_progress_cap(dex));
  select jsonb_agg(jsonb_build_object(
    'dex', (m ->> 'dex')::int,
    'level', least((m ->> 'level')::int, cap),
    'shiny', coalesce((m ->> 'shiny')::boolean, false)
  ) order by t.ord)
  into new_team
  from unnest(p_ids) with ordinality t(id, ord)
  join jsonb_array_elements(coalesce(box, '[]')) m on m ->> 'id' = t.id
  where m ->> 'revivesAt' is null;
  if new_team is null or jsonb_array_length(new_team) <> array_length(p_ids, 1) then raise exception 'events_not_eligible'; end if;
  insert into raid_progress_teams (user_id, realm, raid_key, region, team, ids, updated_at)
  values (me, p_realm, p_key, region, new_team, to_jsonb(p_ids), now())
  on conflict (user_id, realm, raid_key) do update
    set region = excluded.region, team = excluded.team, ids = excluded.ids, updated_at = now();
  return new_team;
end $$;

-- 0045's, with a portal area's raid: closed only once its run is won (the game sends its save just before).
create or replace function raid_progress_close(p_key text, p_helpers uuid[] default '{}', p_realm text default 'main')
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  me uuid := auth.uid();
  dex int := raid_progress_dex(p_key);
  won int;
begin
  if me is null then raise exception 'events_signed_out'; end if;
  if dex is null then raise exception 'events_bad_raid'; end if;
  if raid_progress_portal(p_key) is not null and not raid_progress_portal_won(p_key, p_realm) then
    raise exception 'events_raid_locked';
  end if;
  insert into event_state (user_id, realm) values (me, p_realm) on conflict (user_id, realm) do nothing;
  insert into raid_progress_done (user_id, realm, raid_key, dex) values (me, p_realm, p_key, dex)
  on conflict (user_id, realm, raid_key) do nothing;
  if not found then
    select es.raids_won into won from event_state es where es.user_id = me and es.realm = p_realm;
    return jsonb_build_object('raidsWon', won, 'gifts', 0);
  end if;
  update event_state es set raids_won = es.raids_won + 1, updated_at = now()
    where es.user_id = me and es.realm = p_realm
    returning es.raids_won into won;
  return jsonb_build_object('raidsWon', won, 'gifts', raid_give_gifts(me, p_helpers, dex, p_realm, p_key));
end $$;

revoke all on function portal_run_open() from public, anon, authenticated;
revoke all on function raid_progress_portal(text) from public, anon, authenticated;
revoke all on function raid_progress_portal_won(text, text) from public, anon, authenticated;
revoke all on function raid_progress_set_team(text, text, text[], text) from public;
revoke all on function raid_progress_close(text, uuid[], text) from public;
grant execute on function raid_progress_set_team(text, text, text[], text), raid_progress_close(text, uuid[], text)
  to authenticated;`

async function main() {
  const args = process.argv.slice(2)
  if (args[0] === '--sql') {
    if (!args[1]) throw new Error('Usage: tsx scripts/patch-hh-distortion.ts --sql <out.sql>')
    await writeFile(path.resolve(args[1]), hhDistortionSql())
    console.log(`✓ Distortion World portal run SQL → ${args[1]}`)
    return
  }
  const [input, output] = args
  if (!input || !output)
    throw new Error(
      'Usage: tsx scripts/patch-hh-distortion.ts <in-bundle.json> <out-bundle.json> | --sql <out.sql>',
    )
  const b = JSON.parse(await readFile(path.resolve(input), 'utf8')) as BundleRaw
  await writeFile(path.resolve(output), JSON.stringify(patchHhDistortion(b)))
  console.log(`✓ Distortion World: opens at ${newCount()}, portal run set → ${output}`)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
