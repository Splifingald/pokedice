/**
 * Trick or Treat (docs/28) as a patch over content that has Haunted Hollow already: one Trick or Treat card in each of
 * its ten main areas' decks (10 → 11 cards), the game_config row `trickOrTreat` (its switch Off, its numbers, each
 * area's ghost list), and the server's check of the switch (`trick_or_treat_open()`, SQL only). Nothing else is touched:
 * an area whose deck already says how many Trick or Treat cards it holds keeps it, and so does a ghost list or a number
 * the admin has set.
 *
 * `tsx scripts/patch-hh-trick-or-treat.ts <in-bundle.json> <out-bundle.json>` patches an admin export for
 * `pnpm import-bundle`; `tsx scripts/patch-hh-trick-or-treat.ts --sql <out.sql>` writes the same as a migration
 * (supabase/migrations/0056_trick_or_treat.sql). The content is the content script's (`TRICK_GHOSTS`, the decks), so
 * fresh content (`pnpm haunted-hollow`) and patched content agree.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { BundleRaw, TrickOrTreatConfig } from '../src/engine/types'
import { DEFAULT_CONFIG } from '../src/engine/defaults'
import { REGION_ID, haunted, trickAreas, withTrickLists } from './content-haunted-hollow'

/** The areas that deal a Trick or Treat card, by id, and how many (the content script's decks). */
export function trickDecks(): { areaId: string; copies: number }[] {
  return haunted()
    .areas.filter((a) => (a.encounterWeights.trick ?? 0) > 0)
    .map((a) => ({ areaId: a.id, copies: a.encounterWeights.trick! }))
}

/** The export with Trick or Treat in it. */
export function patchHhTrickOrTreat(b: BundleRaw): BundleRaw {
  if (!b.areas.some((a) => a.regionId === REGION_ID))
    throw new Error('This export has no Haunted Hollow: add it first (pnpm haunted-hollow)')
  const decks = new Map(trickDecks().map((d) => [d.areaId, d.copies]))
  const config = b.config as Record<string, unknown> & { trickOrTreat?: Partial<TrickOrTreatConfig> }
  return {
    ...b,
    areas: b.areas.map((a) =>
      decks.has(a.id) && a.encounterWeights?.trick == null
        ? { ...a, encounterWeights: { ...a.encounterWeights, trick: decks.get(a.id)! } }
        : a,
    ),
    config: {
      ...config,
      configVersion: Number(config.configVersion ?? 0) + 1,
      trickOrTreat: withTrickLists(config.trickOrTreat),
    },
  }
}

const q = (v: string) => `'${v.replace(/'/g, "''")}'`

/**
 * The same as SQL for a live database that ran 0052 (and 0055): the row inserted if missing (Off), or the world's
 * lists added to an admin's row where an area has none; a card in each main area's deck unless its deck already
 * counts them; the switch's server check; `configVersion` + 1 so players fetch the new content. Safe to run again.
 */
export function hhTrickOrTreatSql(): string {
  const row = { ...DEFAULT_CONFIG.trickOrTreat, areas: trickAreas() }
  const decks = trickDecks()
  const byCopies = new Map<number, string[]>()
  for (const d of decks) byCopies.set(d.copies, [...(byCopies.get(d.copies) ?? []), d.areaId])
  return [
    '-- Trick or Treat (docs/28). Generated by `tsx scripts/patch-hh-trick-or-treat.ts --sql`: do not edit by hand.',
    "-- Patches only what it adds, over the admin's later edits: game_config `trickOrTreat` (its switch Off, its numbers,",
    "-- Haunted Hollow's ghost lists; an admin's row keeps its values and own lists), one Trick or Treat card in each of",
    "-- the world's ten main areas (an area whose deck already counts them keeps its number), and trick_or_treat_open(),",
    '-- the switch as the server reads it for the caller (docs/15 §20). Then `configVersion` + 1. Safe to run again.',
    'begin;',
    `insert into game_config (key, value) values ('trickOrTreat', ${q(JSON.stringify(row))}::jsonb)
on conflict (key) do nothing;`,
    `update game_config set value = jsonb_set(value, '{areas}', ${q(JSON.stringify(row.areas))}::jsonb
  || case when jsonb_typeof(value -> 'areas') = 'object' then value -> 'areas' else '{}'::jsonb end)
where key = 'trickOrTreat' and jsonb_typeof(value) = 'object';`,
    ...[...byCopies].map(
      ([
        copies,
        ids,
      ]) => `update areas set encounter_weights = coalesce(encounter_weights, '{}'::jsonb) || '{"trick": ${copies}}'::jsonb
where id in (${ids.map(q).join(', ')})
  and not (coalesce(encounter_weights, '{}'::jsonb) ? 'trick');`,
    ),
    `-- The switch for the caller: on for everyone, or for the admin only (their JWT). An odd value is off.
create or replace function trick_or_treat_open()
returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(a = 'all' or (a = 'admin' and is_admin()), false)
  from (select coalesce((select value ->> 'access' from game_config where key = 'trickOrTreat' and jsonb_typeof(value) = 'object'), 'off') a) x
$$;
revoke all on function trick_or_treat_open() from public;
grant execute on function trick_or_treat_open() to anon, authenticated;`,
    "insert into game_config (key, value) values ('configVersion', '1'::jsonb) on conflict (key) do update set value = to_jsonb(coalesce((game_config.value #>> '{}')::int, 0) + 1);",
    'commit;',
    '',
  ].join('\n')
}

async function main() {
  const args = process.argv.slice(2)
  if (args[0] === '--sql') {
    if (!args[1]) throw new Error('Usage: tsx scripts/patch-hh-trick-or-treat.ts --sql <out.sql>')
    await writeFile(path.resolve(args[1]), hhTrickOrTreatSql())
    console.log(`✓ Trick or Treat SQL → ${args[1]}`)
    return
  }
  const [input, output] = args
  if (!input || !output)
    throw new Error(
      'Usage: tsx scripts/patch-hh-trick-or-treat.ts <in-bundle.json> <out-bundle.json> | --sql <out.sql>',
    )
  const b = JSON.parse(await readFile(path.resolve(input), 'utf8')) as BundleRaw
  await writeFile(path.resolve(output), JSON.stringify(patchHhTrickOrTreat(b)))
  console.log(`✓ Trick or Treat: ${trickDecks().length} areas deal its card → ${output}`)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
